using System.IO;
using System.Text;
using VideoAutoWpf.Models.V2;

namespace VideoAutoWpf.Services;

/// <summary>
/// Dịch vụ xuất phụ đề chuẩn ASS (Advanced SubStation Alpha v4.00+).
/// Khắc phục triệt để lỗi cú pháp drawtext trong FFmpeg của V1.
/// Hỗ trợ Karaoke chạy từng chữ theo thời gian thực (real-time highlight) qua tag {\k...}.
/// </summary>
public static class AssSubtitleService
{
    /// <summary>
    /// Tạo file phụ đề .ass cho toàn bộ timeline của video.
    /// </summary>
    public static async Task<string> GenerateAssFileAsync(
        IReadOnlyList<Scene> scenes,
        string outputPath,
        int width = 1080,
        int height = 1920,
        string fontName = "Segoe UI Bold",
        string subtitleStyle = "cinematic",
        string highlightColor = "#ffd43b",
        CancellationToken ct = default)
    {
        var sb = new StringBuilder();

        // 1. TÍNH TOÁN KÍCH THƯỚC VÀ MÀU SẮC DỰA TRÊN RESOLUTION VÀ STYLE
        int fontSize = width > height ? Math.Max(32, height / 24) : Math.Max(40, height / 32);
        int marginV = width > height ? (int)(height * 0.12) : (int)(height * 0.15);

        // Chuyển hex color (#ffd43b) sang BGR trong ASS format: &H00BBGGRR
        string assPrimaryColor = "&H00FFFFFF"; // Trắng
        string assSecondaryColor = ToAssBgrColor(highlightColor); // Màu highlight Karaoke
        string assOutlineColor = "&H00000000"; // Đen
        string assBackColor = "&H80000000";    // Đen mờ 50%

        int outlineWidth = 4;
        int shadowDepth = 2;

        if (subtitleStyle.Equals("viral_yellow", StringComparison.OrdinalIgnoreCase))
        {
            assPrimaryColor = "&H003BD4FF"; // Vàng #ffd43b
            assSecondaryColor = "&H0000FFFF"; // Vàng sáng
            outlineWidth = 5;
        }
        else if (subtitleStyle.Equals("neon", StringComparison.OrdinalIgnoreCase))
        {
            assPrimaryColor = "&H00EBDC89"; // Neon cyan
            assSecondaryColor = "&H00F5661E";
            outlineWidth = 3;
            shadowDepth = 4;
        }

        // 2. HEADER ASS FORMAT
        sb.AppendLine("[Script Info]");
        sb.AppendLine("; Script generated by VideoAutoWpf V2 AssSubtitleService");
        sb.AppendLine("Title: VideoAutoWpf Subtitles");
        sb.AppendLine("ScriptType: v4.00+");
        sb.AppendLine("WrapStyle: 0");
        sb.AppendLine("ScaledBorderAndShadow: yes");
        sb.AppendLine($"PlayResX: {width}");
        sb.AppendLine($"PlayResY: {height}");
        sb.AppendLine();

        // 3. STYLES
        sb.AppendLine("[V4+ Styles]");
        sb.AppendLine("Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding");
        sb.AppendLine($"Style: Default,{fontName},{fontSize},{assPrimaryColor},{assSecondaryColor},{assOutlineColor},{assBackColor},-1,0,0,0,100,100,0,0,1,{outlineWidth},{shadowDepth},2,20,20,{marginV},1");
        sb.AppendLine();

        // 4. EVENTS
        sb.AppendLine("[Events]");
        sb.AppendLine("Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text");

        double currentTimelineOffset = 0.0;

        foreach (var scene in scenes)
        {
            double sceneDur = scene.AudioDurationSeconds > 0.1 ? scene.AudioDurationSeconds : 5.0;

            if (scene.WordTimestamps != null && scene.WordTimestamps.Count > 0)
            {
                // CHẾ ĐỘ KARAOKE: Nhóm các từ thành từng dòng và áp dụng tag {\k<centiseconds>}
                int maxCharsPerLine = width > height ? 40 : 28;
                var lines = GroupWordsIntoLines(scene.WordTimestamps, maxCharsPerLine);

                foreach (var line in lines)
                {
                    double lineStart = currentTimelineOffset + line.Words.First().StartTime;
                    double lineEnd = currentTimelineOffset + line.Words.Last().EndTime;

                    var startFormatted = FormatAssTime(lineStart);
                    var endFormatted = FormatAssTime(lineEnd);

                    var textBuilder = new StringBuilder();
                    for (int wIdx = 0; wIdx < line.Words.Count; wIdx++)
                    {
                        var word = line.Words[wIdx];
                        int centiseconds = Math.Max(5, (int)Math.Round((word.EndTime - word.StartTime) * 100));
                        textBuilder.Append($"{{\\k{centiseconds}}}{word.Word} ");
                    }

                    sb.AppendLine($"Dialogue: 0,{startFormatted},{endFormatted},Default,,0,0,0,,{textBuilder.ToString().Trim()}");
                }
            }
            else if (!string.IsNullOrWhiteSpace(scene.NarrationText))
            {
                // CHẾ ĐỘ THƯỜNG: Hiển thị nguyên câu thoại có ngắt dòng
                double lineStart = currentTimelineOffset;
                double lineEnd = currentTimelineOffset + sceneDur;

                var startFormatted = FormatAssTime(lineStart);
                var endFormatted = FormatAssTime(lineEnd);

                int maxChars = width > height ? 42 : 30;
                var wrappedText = WrapTextForAss(scene.NarrationText.Trim(), maxChars);

                sb.AppendLine($"Dialogue: 0,{startFormatted},{endFormatted},Default,,0,0,0,,{wrappedText}");
            }

            currentTimelineOffset += sceneDur;
        }

        var dir = Path.GetDirectoryName(outputPath);
        if (!string.IsNullOrEmpty(dir))
            Directory.CreateDirectory(dir);

        await File.WriteAllTextAsync(outputPath, sb.ToString(), new UTF8Encoding(false), ct);
        return outputPath;
    }

    private static string FormatAssTime(double seconds)
    {
        var ts = TimeSpan.FromSeconds(Math.Max(0, seconds));
        int centiseconds = (int)(ts.Milliseconds / 10.0);
        return $"{(int)ts.TotalHours}:{ts.Minutes:D2}:{ts.Seconds:D2}.{centiseconds:D2}";
    }

    private static string ToAssBgrColor(string hex)
    {
        if (string.IsNullOrWhiteSpace(hex)) return "&H003BD4FF";
        hex = hex.Trim().TrimStart('#');
        if (hex.Length == 6)
        {
            var r = hex.Substring(0, 2);
            var g = hex.Substring(2, 2);
            var b = hex.Substring(4, 2);
            // ASS format là &H00BBGGRR
            return $"&H00{b}{g}{r}";
        }
        return "&H003BD4FF";
    }

    private static string WrapTextForAss(string text, int maxCharsPerLine)
    {
        var words = text.Split(new[] { ' ', '\t', '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries);
        var sb = new StringBuilder();
        var currentLine = new StringBuilder();

        foreach (var word in words)
        {
            if (currentLine.Length + word.Length + 1 > maxCharsPerLine)
            {
                if (currentLine.Length > 0)
                {
                    if (sb.Length > 0) sb.Append("\\N");
                    sb.Append(currentLine.ToString());
                    currentLine.Clear();
                }
            }
            if (currentLine.Length > 0) currentLine.Append(' ');
            currentLine.Append(word);
        }

        if (currentLine.Length > 0)
        {
            if (sb.Length > 0) sb.Append("\\N");
            sb.Append(currentLine.ToString());
        }

        return sb.ToString();
    }

    private static List<WordLine> GroupWordsIntoLines(List<WordTimestamp> words, int maxChars)
    {
        var lines = new List<WordLine>();
        var currentWords = new List<WordTimestamp>();
        int currentLen = 0;

        foreach (var w in words)
        {
            if (currentLen + w.Word.Length + 1 > maxChars && currentWords.Count > 0)
            {
                lines.Add(new WordLine(currentWords));
                currentWords = new List<WordTimestamp>();
                currentLen = 0;
            }
            currentWords.Add(w);
            currentLen += w.Word.Length + 1;
        }

        if (currentWords.Count > 0)
            lines.Add(new WordLine(currentWords));

        return lines;
    }

    private class WordLine
    {
        public List<WordTimestamp> Words { get; }
        public WordLine(List<WordTimestamp> words) => Words = new List<WordTimestamp>(words);
    }
}
